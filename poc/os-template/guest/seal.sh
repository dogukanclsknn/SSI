#!/usr/bin/env bash
# Turns the patched build VM into a template: removes everything that belongs to this one
# machine or to the build, so every VM created from the template gets its own identity on first
# boot. Runs as root inside the build VM as the last step; the build user itself (its SSH key and
# sudo rule) is removed by the shutdown command right after this.
#
# TEMPLATE_NAME, TEMPLATE_VERSION, BUILD_ID: recorded in /etc/ssi-template-release.
set -euo pipefail

: "${TEMPLATE_NAME:?}" "${TEMPLATE_VERSION:?}" "${BUILD_ID:?}"

# Build tooling and package caches.
rm -rf /var/tmp/ssi-scan
apt-get clean
rm -rf /var/lib/apt/lists/*

# Traceability inside every VM made from this template.
cat > /etc/ssi-template-release <<RELEASE
SSI_TEMPLATE_NAME=${TEMPLATE_NAME}
SSI_TEMPLATE_VERSION=${TEMPLATE_VERSION}
SSI_TEMPLATE_BUILD_ID=${BUILD_ID}
SSI_TEMPLATE_SEALED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
RELEASE
chmod 0644 /etc/ssi-template-release

# Identity: cloud-init runs again on first boot (new instance, network, SSH host keys, users);
# the machine ID is regenerated by systemd.
if ! cloud-init clean --logs --seed --machine-id; then
  cloud-init clean --logs --seed
  truncate -s 0 /etc/machine-id
fi
if [[ -d /var/lib/dbus ]]; then
  rm -f /var/lib/dbus/machine-id
  ln -s /etc/machine-id /var/lib/dbus/machine-id
fi
rm -f /etc/ssh/ssh_host_*

# History and logs of the build.
rm -f /root/.bash_history
find /home -maxdepth 2 -name .bash_history -delete
journalctl --rotate >/dev/null 2>&1 || true
journalctl --vacuum-time=1s >/dev/null 2>&1 || true
find /var/log -type f \( -name '*.gz' -o -name '*.[0-9]' -o -name '*.old' \) -delete
find /var/log -type f -exec truncate -s 0 {} +

# Free blocks, so the exported disk compresses well.
fstrim -av >/dev/null 2>&1 || true
sync
echo "Sealed ${TEMPLATE_NAME} ${TEMPLATE_VERSION} (build ${BUILD_ID})."
